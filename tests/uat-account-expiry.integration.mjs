import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const directory = mkdtempSync(join(tmpdir(), 'bw-uat-expiry-'));
Object.assign(process.env, { NODE_ENV: 'production', BUBBLEWASH_UAT_ENABLED: 'true', BUBBLEWASH_UAT_ISOLATION_CONFIRMED: 'true', BUBBLEWASH_PUBLIC_URL: 'https://uat.example.invalid', BUBBLEWASH_DATABASE_PATH: join(directory,'synthetic.sqlite'), BUBBLEWASH_UAT_DATA_ROOT: directory, NEXT_PUBLIC_BUBBLEWASH_ONLINE_PAYMENTS_ENABLED:'false', NEXT_PUBLIC_BUBBLEWASH_AUTOMATED_UPDATES_ENABLED:'false', BUBBLEWASH_RESEARCH_EMAIL_ENABLED:'false', BUBBLEWASH_DISABLE_DEMO_LOGIN:'true', BUBBLEWASH_SESSION_SECRET:'synthetic-session-secret-only-for-test-123' });
const { getDatabase } = await import('../src/lib/data-store.ts');
const { createUatAccount, revokeUatAccount, UAT_WINDOW_MS } = await import('../src/lib/uat-accounts.ts');
const auth = await import('../src/lib/auth.ts');
const database = getDatabase();
const realNow = Date.now;
let now = Math.floor(realNow()/1000)*1000 + 1000;
Date.now = () => now;
const account = { username:'review-admin', name:'Synthetic reviewer', role:'admin', password:'synthetic-long-uat-password-only', startsAt:now+1000 };
try {
  const created = createUatAccount(account, 'synthetic-coordinator');
  assert.equal(created.expiresAt-created.startsAt, UAT_WINDOW_MS);
  assert.equal(auth.findStaffUser(account.username, account.password), null, 'not usable before agreed start');
  now = created.startsAt;
  let user = auth.findStaffUser(account.username.toUpperCase(), account.password);
  assert.equal(user.role, 'admin'); assert.equal(user.temporaryAccess,true); assert.equal(user.allStaffAccess,false);
  assert.equal(auth.findStaffUser('nonexistent',account.password),null);
  assert.equal(auth.findStaffUser(account.username,'wrong'),null);
  assert.throws(() => createUatAccount({...account,startsAt:now+1000},'coordinator'), /UNIQUE/);
  const first = auth.encodeSession(user);
  assert.equal(auth.decodeSession(first).temporaryAccess,true);
  now += 8*60*60*1000;
  assert.equal(auth.decodeSession(first),null,'eight-hour session exact cutoff');
  assert.ok(auth.findStaffUser(account.username,account.password),'new session allowed before account deadline');
  now = created.expiresAt-1000;
  user = auth.findStaffUser(account.username,account.password);
  const late = auth.encodeSession(user);
  const payload = JSON.parse(Buffer.from(late.split('.')[0],'base64url'));
  assert.equal(payload.expiresAt,created.expiresAt/1000,'late session is capped at account deadline');
  assert.ok(auth.decodeSession(late));
  now = created.expiresAt;
  assert.equal(auth.findStaffUser(account.username,account.password),null,'login denied at exact deadline');
  assert.equal(auth.decodeSession(late),null,'already-open session revoked at deadline');
  assert.equal(database.prepare("SELECT status FROM staff_uat_accounts WHERE username=?").get(account.username).status,'expired');
  assert.equal(database.prepare("SELECT COUNT(*) AS n FROM staff_uat_audit WHERE action='expired'").get().n,1);
  auth.currentStaffUsers();
  assert.equal(database.prepare("SELECT COUNT(*) AS n FROM staff_uat_audit WHERE action='expired'").get().n,1,'expiry audit idempotent');
  const second = {...account,username:'review-support',role:'support',startsAt:now};
  createUatAccount(second,'coordinator');
  const active=auth.encodeSession(auth.findStaffUser(second.username,second.password));
  revokeUatAccount(second.username,'coordinator');
  assert.equal(auth.decodeSession(active),null,'manual revocation affects existing sessions');
  assert.equal(auth.findStaffUser(second.username,second.password),null);
  assert.throws(()=>createUatAccount(second,'coordinator'),/UNIQUE/,'revoked usernames cannot reset expiry');
  assert.throws(()=>createUatAccount({...account,username:'email@example.invalid',startsAt:now},'coordinator'));
  assert.throws(()=>createUatAccount({...account,username:'missing-vendor',role:'vendor',startsAt:now},'coordinator'));
  createUatAccount({...account,username:'environment-check',startsAt:now},'coordinator');
  const safe=auth.encodeSession(auth.findStaffUser('environment-check',account.password));
  process.env.BUBBLEWASH_PUBLIC_URL='https://staff.bubblewash.co';
  assert.equal(auth.decodeSession(safe),null,'unsafe environment denies existing session');
  assert.equal(auth.findStaffUser('environment-check',account.password),null);
  process.env.BUBBLEWASH_UAT_ENABLED='false';
  assert.equal(auth.decodeSession(safe),null,'UAT accounts unavailable outside UAT');
  assert.equal(database.prepare("SELECT 1 FROM sqlite_master WHERE name='staff_owner_capabilities'").get(),undefined,'no owner capabilities created');
  console.log('UAT usernames, fixed 168h expiry, session cutoff, manual revoke, no extension and environment fail-closed: passed');
} finally { Date.now=realNow; database.close(); rmSync(directory,{recursive:true,force:true}); }
