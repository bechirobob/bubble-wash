import { test, expect } from '@playwright/test';

test('archive requires confirmation, cancels safely and stays recoverable', async ({ page }, testInfo) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === 'localhost' ? route.continue() : route.abort());
  await page.goto('/login?next=%2Fadmin');
  await page.getByLabel('Staff username or email').fill('admin@example.invalid');
  await page.getByLabel('Password', { exact: true }).fill('synthetic-admin-password-123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/admin/);
  const email = `archive-${testInfo.project.name}@example.invalid`;
  const created = await page.request.post('/api/staff/accounts', { headers: { origin: 'http://localhost:3100' }, data: { email, name: 'Archive test', role: 'support', entityId: '' } });
  expect(created.status()).toBe(200);
  await page.goto('/admin?view=people');
  const panel = page.locator('.staffAccountPanel');
  const row = panel.locator('.staffCaseRow').filter({ hasText: email });
  await row.getByRole('button', { name: 'Archive staff', exact: true }).click();
  const confirmation = panel.getByRole('form', { name: 'Confirm account archive' });
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(confirmation).toHaveCount(0);
  await expect(row).toBeVisible();
  await row.getByRole('button', { name: 'Archive staff', exact: true }).click();
  await confirmation.getByRole('textbox').fill('wrong@example.invalid');
  await confirmation.getByRole('button', { name: 'Confirm archive', exact: true }).click();
  await expect(panel.locator(':scope > p[role="status"]')).toContainText('Confirm the account email');
  await expect(row).toBeVisible();
  await confirmation.getByRole('textbox').fill(email);
  await panel.screenshot({ path: testInfo.outputPath('staff-archive-confirmation.png') });
  await confirmation.getByRole('button', { name: 'Confirm archive', exact: true }).click();
  await expect(panel.locator(':scope > p[role="status"]')).toContainText('Sign-in account archived');
  await expect(row).toHaveCount(0);
  await panel.getByLabel('Show archived accounts').check();
  await expect(row).toContainText('archived');
  await expect(row.getByRole('button')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await panel.screenshot({ path: testInfo.outputPath('staff-archive-archived.png') });
  await panel.locator('summary').click();
  const restore = panel.locator('details form');
  await restore.getByLabel('Name', { exact: true }).fill('Archive test');
  await restore.getByLabel('Work email', { exact: true }).fill(email);
  await restore.getByRole('button', { name: 'Create activation link', exact: true }).click();
  await expect(panel.locator(':scope > p[role="status"]')).toContainText('Confirm restoration');
  await restore.getByLabel('Restore this account if archived').check();
  await restore.getByRole('button', { name: 'Create activation link', exact: true }).click();
  await expect(panel.locator('code')).toBeVisible();
  const activationLink = await panel.locator('code').textContent();
  await expect(row).toContainText('invited');
  await panel.screenshot({ path: testInfo.outputPath('staff-archive-restored.png') });
  await page.goto(activationLink);
  await page.getByLabel('New password', { exact: true }).fill('synthetic-restored-password-123');
  await page.getByRole('button', { name: 'Activate access', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Access activated');
  await page.request.post('/api/logout', { headers: { origin: 'http://localhost:3100' } });
  await page.goto('/login');
  await page.getByLabel('Staff username or email').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('synthetic-restored-password-123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/support/);

});
