import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const directory = mkdtempSync(join(tmpdir(), 'bw-uat-expiry-'));
Object.assign(process.env, { NODE_ENV: 'production', BUBBLEWASH_UAT_ENABLED: 'true', BUBBLEWASH_UAT_ISOLATION_CONFIRMED: 'true', BUBBLEWASH_PUBLIC_URL: 'https://uat.example.invalid', BUBBLEWASH_DATABASE_PATH: join(directory,'synthetic.sqlite'), BUBBLEWASH_UAT_DATA_ROOT: directory, NEXT_PUBLIC_BUBBLEWASH_ONLINE_PAYMENTS_ENABLED:'false', NEXT_PUBLIC_BUBBLEWASH_AUTOMATED_UPDATES_ENABLED:'false', BUBBLEWASH_RESEARCH_EMAIL_ENABLED:'false', BUBBLEWASH_DISABLE_DEMO_LOGIN:'true', BUBBLEWASH_SESSION_SECRET:'synthetic-session-secret-only-for-test-123' });
const { getDatabase } = await import('../src/lib/data-store.ts');
const { createUatAccount, revokeUatAccount, UAT_WINDOW_MS, extendUatCohort, currentUatUsers, listUatTeam, createUatTeamAccount, revokeUatTeamAccount } = await import('../src/lib/uat-accounts.ts');
const auth = await import('../src/lib/auth.ts');
const database = getDatabase();
const realNow = Date.now;
let now = Math.floor(realNow()/1000)*1000 + 1000;
Date.now = () => now;
const account = { username:'review-admin', name:'Synthetic reviewer', role:'admin', password:'synthetic-long-uat-password-only', startsAt:now+1000 };
try {
  const startsAt = now;
  const expiresAt = startsAt + UAT_WINDOW_MS;
  const make = (username, role='support', start=startsAt) => createUatAccount({...account,username,role,startsAt:start},'test');
  make('review-admin','admin'); make('review-support'); make('review-revoked');
  make('other-cohort','admin',startsAt+1);
  revokeUatAccount('review-revoked','test');
  const before=database.prepare('SELECT * FROM staff_uat_accounts ORDER BY username').all();
  const admin=auth.findStaffUser('review-admin',account.password);
  const session=auth.encodeSession(admin);
  const request={startsAt,originalExpiresAt:expiresAt,expiresAt:expiresAt+UAT_WINDOW_MS,expectedUsernames:['review-admin','review-support'],operationId:'synthetic-extension-001'};
  assert.throws(()=>extendUatCohort({...request,expectedUsernames:['review-admin']},'test'));
  assert.throws(()=>extendUatCohort({...request,expiresAt:request.expiresAt+1},'test'));
  database.exec("CREATE TRIGGER fail_extension BEFORE INSERT ON staff_uat_audit WHEN NEW.action='extended-seven-days' AND NEW.username='review-support' BEGIN SELECT RAISE(ABORT,'synthetic audit failure'); END");
  assert.throws(()=>extendUatCohort(request,'test'),/synthetic audit failure/);
  assert.equal(database.prepare("SELECT 1 FROM sqlite_master WHERE name='staff_uat_extensions'").get(),undefined,'DDL and partial inserts roll back');
  assert.deepEqual(database.prepare('SELECT * FROM staff_uat_accounts ORDER BY username').all(),before);
  database.exec('DROP TRIGGER fail_extension');
  assert.deepEqual(extendUatCohort(request,'test'),{extended:2,total:2,expiresAt:request.expiresAt});
  assert.deepEqual(database.prepare('SELECT * FROM staff_uat_accounts ORDER BY username').all(),before,'all original fields unchanged');
  assert.equal(extendUatCohort(request,'test').extended,0,'same operation idempotent');
  assert.throws(()=>extendUatCohort({...request,operationId:'different-operation'},'test'));
  assert.equal(database.prepare("SELECT COUNT(*) n FROM staff_uat_audit WHERE action='extended-seven-days'").get().n,2);
  assert.ok(auth.decodeSession(session),'existing cookie preserved');
  assert.equal(auth.findStaffUser('review-admin',account.password).accessExpiresAt,request.expiresAt);
  assert.equal(auth.findStaffUser('review-revoked',account.password),null);
  const actor={email:'review-admin',role:'admin',temporaryAccess:true};
  const team=listUatTeam(actor); assert.equal(team.expiresAt,request.expiresAt);
  assert.equal(team.accounts.length,2,'revoked membership retained'); assert.equal(team.remaining,17);
  database.prepare("UPDATE staff_uat_extensions SET credential_version='mismatch' WHERE username='review-admin'").run();
  assert.equal(auth.findStaffUser('review-admin',account.password).accessExpiresAt,expiresAt,'grant cannot follow changed credentials');
  database.prepare("UPDATE staff_uat_extensions SET credential_version=? WHERE username='review-admin'").run(admin.credentialVersion);
  now=expiresAt;
  assert.ok(auth.findStaffUser('review-admin',account.password),'same password works beyond original expiry');
  assert.equal(auth.decodeSession(session),null,'old cookie retains its own cutoff');
  assert.equal(database.prepare("SELECT status FROM staff_uat_accounts WHERE username='review-admin'").get().status,'active');
  assert.throws(()=>createUatTeamAccount({...account,username:'new-user',role:'support'},actor));
  assert.throws(()=>extendUatCohort(request,'test'),'no fresh writes after original cutoff');
  revokeUatTeamAccount('review-support',actor);
  assert.equal(auth.findStaffUser('review-support',account.password),null,'extension does not bypass revocation');
  const fresh=auth.encodeSession(auth.findStaffUser('review-admin',account.password)); assert.ok(auth.decodeSession(fresh));
  now=request.expiresAt-1; assert.ok(auth.findStaffUser('review-admin',account.password));
  now=request.expiresAt; assert.equal(auth.findStaffUser('review-admin',account.password),null,'exact new deadline enforced');
  assert.equal(database.prepare("SELECT status FROM staff_uat_accounts WHERE username='review-admin'").get().status,'expired');
  assert.equal(auth.decodeSession(fresh),null);
  process.env.BUBBLEWASH_UAT_ENABLED='false'; assert.throws(()=>extendUatCohort(request,'test'));
  console.log('UAT explicit extension, original records, revoked users, cohort, session and deadline checks passed');
} finally { Date.now=realNow; database.close(); rmSync(directory,{recursive:true,force:true}); }
