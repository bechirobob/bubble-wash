import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { NextRequest } from "next/server";
import { createPasswordHash } from "../src/lib/passwords.ts";
import { totpCode } from "../src/lib/totp.ts";
const globalMfa = process.argv.includes("--global-off") ? "false" : "true";
const dir = mkdtempSync(join(tmpdir(), "bw-owner-mfa-"));
Object.assign(process.env, { BUBBLEWASH_TRUST_PROXY_HEADERS: "true", NODE_ENV: "production", BUBBLEWASH_DATABASE_PATH: join(dir, "auth.sqlite"), BUBBLEWASH_DISABLE_DEMO_LOGIN: "true", BUBBLEWASH_ADMIN_EMAIL: "master@example.invalid", BUBBLEWASH_ADMIN_TOTP_SECRET: "JBSWY3DPEHPK3PXPJBSWY3DPEHPK3PXP", BUBBLEWASH_ADMIN_MFA_REQUIRED: globalMfa, NEXT_PUBLIC_BUBBLEWASH_ADMIN_MFA_REQUIRED: globalMfa, BUBBLEWASH_ADMIN_PASSWORD_HASH: createPasswordHash("synthetic-master-long-password"), BUBBLEWASH_SESSION_SECRET: "synthetic-session-key-long-enough-12345", BUBBLEWASH_MFA_ENCRYPTION_KEY: Buffer.alloc(32, 23).toString("base64") });
const { inviteOwnerAccount } = await import("../src/lib/staff-accounts.ts");
const mfa = await import("../src/lib/admin-mfa.ts");
const { getDatabase } = await import("../src/lib/data-store.ts");
const { POST: activate } = await import("../src/app/api/staff/activate/route.ts");
const { POST: enroll } = await import("../src/app/api/admin/mfa/enroll/route.ts");
const { POST: login } = await import("../src/app/api/login/route.ts");
let requestId = 1;
function request(path, body) { return new NextRequest(`https://bubblewash.co${path}`, { method: "POST", headers: { origin: "https://bubblewash.co", host: "bubblewash.co", "content-type": "application/json", "x-forwarded-for": `192.0.2.${requestId++}` }, body: JSON.stringify(body) }); }
const auth = await import("../src/lib/auth.ts");
const ownerCredentials = { email: "owner@example.invalid", password: "synthetic-owner-long-password" };
try {
  const token = inviteOwnerAccount({ email: "owner@example.invalid", name: "Personal Owner" }, "fixture");
  const activated = await activate(request("/api/staff/activate", { token, password: ownerCredentials.password }));
  assert.equal(activated.status, 200); assert.equal(activated.headers.get("set-cookie"), null);
  for (const credentials of [{ ...ownerCredentials, password: "wrong-password" }, { email: "missing@example.invalid", password: ownerCredentials.password }]) {
    const rejected = await login(request("/api/login", credentials));
    assert.equal(rejected.status, 401); assert.equal((await rejected.json()).mfaStep, undefined); assert.equal(rejected.headers.get("set-cookie"), null);
  }
  const ownerIdentity = auth.findStaffUser(ownerCredentials.email, ownerCredentials.password);
  assert.throws(() => auth.encodeSession(ownerIdentity), /MFA verification/);
  assert.throws(() => auth.encodeSession(ownerIdentity, true), /MFA verification/);
  const legacyOwnerCookie = auth.encodeSession({ ...ownerIdentity, allStaffAccess: false });
  assert.equal(auth.decodeSession(legacyOwnerCookie), null);
  if (globalMfa === "false") {
    assert.equal((await login(request("/api/login", { email: "master@example.invalid", password: "synthetic-master-long-password" }))).status, 200);
  }
  const step = Math.floor(Date.now() / 30000);
  assert.equal((await login(request("/api/login", { email: "master@example.invalid", password: "synthetic-master-long-password", totp: totpCode(process.env.BUBBLEWASH_ADMIN_TOTP_SECRET, step) }))).status, 200);
  const needsEnrollment = await login(request("/api/login", { ...ownerCredentials, totp: totpCode(process.env.BUBBLEWASH_ADMIN_TOTP_SECRET, step) }));
  assert.equal(needsEnrollment.status, 403); assert.equal((await needsEnrollment.json()).mfaStep, "enroll"); assert.equal(needsEnrollment.headers.get("set-cookie"), null);
  assert.equal(mfa.adminTotpSecret("master@example.invalid"), process.env.BUBBLEWASH_ADMIN_TOTP_SECRET);
  assert.equal(mfa.adminMfaEnrollmentExists("owner@example.invalid"), false);
  assert.equal(mfa.adminMfaConfigured("owner@example.invalid"), false);
  assert.equal(mfa.verifyAdminMfaCredential("owner@example.invalid", totpCode(process.env.BUBBLEWASH_ADMIN_TOTP_SECRET)), false);
  const masterBefore = getDatabase().prepare("SELECT * FROM admin_mfa_settings WHERE admin_email = 'master@example.invalid'").get();
  const started = await enroll(request("/api/admin/mfa/enroll", { ...ownerCredentials, action: "start" }));
  assert.equal(started.status, 200);
  const { enrollment } = await started.json();
  assert.equal(started.headers.get("set-cookie"), null);
  assert.equal(auth.decodeSession(legacyOwnerCookie), null);
  assert.notEqual(enrollment.manualKey, process.env.BUBBLEWASH_ADMIN_TOTP_SECRET);
  const confirmation = await enroll(request("/api/admin/mfa/enroll", { ...ownerCredentials, action: "confirm", code: totpCode(enrollment.manualKey, step) }));
  assert.equal(confirmation.status, 200);
  const confirmed = await confirmation.json();
  const session = confirmation.cookies.get(auth.sessionCookieName)?.value;
  assert.ok(session); assert.equal(auth.decodeSession(session).allStaffAccess, true);
  assert.equal(auth.decodeSession(legacyOwnerCookie), null);
  assert.throws(() => auth.encodeSession(ownerIdentity), /MFA verification/);
  const needsCode = await login(request("/api/login", ownerCredentials));
  assert.equal(needsCode.status, 401); assert.equal((await needsCode.json()).mfaStep, "verify"); assert.equal(needsCode.headers.get("set-cookie"), null);
  const resumeOld = request("/api/admin/mfa/enroll", { action: "resume" });
  resumeOld.cookies.set(auth.sessionCookieName, legacyOwnerCookie);
  assert.equal((await enroll(resumeOld)).status, 401);
  const acknowledge = request("/api/admin/mfa/enroll", { action: "acknowledge" });
  acknowledge.cookies.set(auth.sessionCookieName, session);
  assert.equal((await enroll(acknowledge)).status, 200); assert.ok(auth.decodeSession(session));
  assert.equal(confirmed.ok, true); assert.equal(confirmed.recoveryCodes.length, 8);
  assert.equal(mfa.adminTotpSecret("owner@example.invalid"), enrollment.manualKey);
  assert.equal(mfa.adminTotpSecret("master@example.invalid"), process.env.BUBBLEWASH_ADMIN_TOTP_SECRET);
  assert.equal(mfa.verifyAdminMfaCredential("master@example.invalid", confirmed.recoveryCodes[0]), false);
  const ownerValidCodes = [-1, 0, 1].map((offset) => totpCode(enrollment.manualKey, step + offset));
  const masterOnlyCode = [-1, 0, 1].map((offset) => totpCode(process.env.BUBBLEWASH_ADMIN_TOTP_SECRET, step + offset)).find((code) => !ownerValidCodes.includes(code));
  assert.ok(masterOnlyCode);
  const badCode = await login(request("/api/login", { ...ownerCredentials, totp: masterOnlyCode }));
  assert.equal(badCode.status, 401); assert.equal((await badCode.json()).mfaStep, "verify"); assert.equal(badCode.headers.get("set-cookie"), null);
  assert.equal((await login(request("/api/login", { ...ownerCredentials, totp: totpCode(enrollment.manualKey, step + 1) }))).status, 200);
  assert.equal((await login(request("/api/login", { ...ownerCredentials, totp: confirmed.recoveryCodes[0] }))).status, 200);
  assert.equal((await login(request("/api/login", { ...ownerCredentials, totp: confirmed.recoveryCodes[0] }))).status, 401);
  assert.equal((await enroll(request("/api/admin/mfa/enroll", { email: "master@example.invalid", password: "synthetic-master-long-password", action: "start" }))).status, 409);
  assert.deepEqual(getDatabase().prepare("SELECT * FROM admin_mfa_settings WHERE admin_email = 'master@example.invalid'").get(), masterBefore);
  const db = getDatabase();
  db.prepare("UPDATE staff_accounts SET status='suspended' WHERE email=?").run(ownerCredentials.email);
  assert.equal(auth.decodeSession(session), null);
  db.prepare("UPDATE staff_accounts SET status='active' WHERE email=?").run(ownerCredentials.email);
  db.prepare("UPDATE admin_mfa_settings SET status='pending' WHERE admin_email=?").run(ownerCredentials.email);
  assert.equal(auth.decodeSession(session), null);
  db.prepare("UPDATE admin_mfa_settings SET status='enrolled' WHERE admin_email=?").run(ownerCredentials.email);
  assert.ok(auth.decodeSession(session));
  const setting = db.prepare("SELECT encrypted_secret FROM admin_mfa_settings WHERE admin_email=?").get(ownerCredentials.email);
  db.prepare("UPDATE admin_mfa_settings SET encrypted_secret='invalid' WHERE admin_email=?").run(ownerCredentials.email);
  assert.equal(auth.decodeSession(session), null);
  const unavailable = await login(request("/api/login", ownerCredentials));
  assert.equal(unavailable.status, 503); assert.equal((await unavailable.json()).mfaStep, undefined); assert.equal(unavailable.headers.get("set-cookie"), null);
  db.prepare("UPDATE admin_mfa_settings SET encrypted_secret=? WHERE admin_email=?").run(setting.encrypted_secret, ownerCredentials.email);
  db.prepare("UPDATE staff_accounts SET credential_version='revoked' WHERE email=?").run(ownerCredentials.email);
  assert.equal(auth.decodeSession(session), null);
  console.log(JSON.stringify({ ok: true, globalMfa, scope: "production owner activation, isolated MFA enrollment and login; master code rejected, owner recovery single-use, legacy master unchanged" }));
} finally { rmSync(dir, { recursive: true, force: true }); }
